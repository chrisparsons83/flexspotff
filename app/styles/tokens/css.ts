import { type Oklch, round } from './color';
import { fillEdges, fills, neutralSteps, textOn, themeRoles } from './palette';
import { scaleTokens } from './scale';

export const TOKENS_CSS_PATH = 'app/styles/tokens.css';

/**
 * Written as bare OKLCH channels so Tailwind can add opacity:
 * `oklch(var(--league-admiral) / <alpha-value>)`.
 */
const channels = (color: Oklch) => {
  const { l, c, h } = round(color);
  return `${l} ${c} ${h}`;
};

const declarations = (tokens: Record<string, Oklch>) =>
  Object.entries(tokens).map(
    ([name, color]) => `  --${name}: ${channels(color)};`,
  );

/**
 * One class drives both the tokens and Tailwind's `dark:` variants: the
 * server always renders `dark` or nothing on <html>, dark by default. Neutral
 * steps and fills are the same in both themes; only the roles and fill edges
 * change.
 */
export const renderTokensCss = () => {
  const fixed = {
    ...Object.fromEntries(neutralSteps.map((c, i) => [`neutral-${i}`, c])),
    ...Object.fromEntries(
      Object.entries(fills).flatMap(([name, c]) => [
        [name, c],
        [`${name}-foreground`, textOn(c)],
      ]),
    ),
  };

  return [
    '/* Generated by `npm run generate:tokens` from app/styles/tokens. Do not edit. */',
    '',
    ':root {',
    '  color-scheme: light;',
    ...Object.entries(scaleTokens).map(
      ([name, value]) => `  --${name}: ${value};`,
    ),
    '',
    ...declarations(fixed),
    '',
    ...declarations(themeRoles('light')),
    '',
    ...declarations(fillEdges('light')),
    '}',
    '',
    ':root.dark {',
    '  color-scheme: dark;',
    ...declarations(themeRoles('dark')),
    '',
    ...declarations(fillEdges('dark')),
    '}',
    '',
  ].join('\n');
};
