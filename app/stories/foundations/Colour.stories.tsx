/** Category fills whose edge is a neutral step in the given theme. */
const edged = (theme: 'dark' | 'light') => {
  const edges = fillEdges(theme);
  const { input } = themeRoles(theme);
  return Object.keys(edges)
    .filter(name => edges[name] === input)
    .map(name => name.replace(/-edge$/, ''));
};

function CategoryTable({
  prefix,
  colors,
  label,
}: {
  prefix: string;
  colors: Record<string, Oklch>;
  label: (name: string) => string;
}) {
  const edgedDark = edged('dark');
  const edgedLight = edged('light');
  return (
    <TokenTable columns={['Fill', 'Token', 'Hex', 'Edge dark', 'Edge light']}>
      {Object.entries(colors).map(([name, color]) => {
        const token = `${prefix}-${name}`;
        return (
          <TokenRow
            key={name}
            cells={[
              <Fill key='f' token={token} label={label(name)} />,
              <Name key='n'>{token}</Name>,
              hex(color),
              edgedDark.includes(token) ? 'Neutral' : 'Matches fill',
              edgedLight.includes(token) ? 'Neutral' : 'Matches fill',
            ]}
          />
        );
      })}
    </TokenTable>
  );
}

