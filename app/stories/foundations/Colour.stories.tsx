/** A block of a token, with an optional edge token drawn around it. */
function Swatch({
  token,
  edge,
  size = 'md',
}: {
  token: string;
  edge?: string;
  size?: 'md' | 'lg';
}) {
  return (
    <span
      aria-hidden
      className={size === 'md' ? 'block size-8' : 'block h-12 w-24'}
      style={{
        background: tokenColor(token),
        border: edge ? `1px solid ${tokenColor(edge)}` : undefined,
      }}
    />
  );
}

/** A fill with its own name set on it in its foreground colour. */
function Fill({ token, label }: { token: string; label: string }) {
  return (
    <span
      className='flex h-12 w-24 items-center px-3 text-sm font-bold'
      style={{
        background: tokenColor(token),
        color: tokenColor(`${token}-foreground`),
        border: `1px solid ${tokenColor(`${token}-edge`)}`,
      }}
    >
      {label}
    </span>
  );
}

